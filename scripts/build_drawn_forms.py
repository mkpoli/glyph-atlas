"""Build what the site reads of the drawn forms: their fonts and the Worker's table.

A drawn form (data/vocab/drawn-forms.yaml, docs/decisions/0014-drawn-forms.md) is a private-use code
point with a drawing in two styles. Each style's font gives every code point its drawing as a glyph,
so a form is set as text wherever a character is; a font's `unicode-range` is the table's code points,
so a page that shows none never downloads it. A file is named by its content hash, so a browser may
keep it for good.

    uv run scripts/build_drawn_forms.py

Writes apps/review/static/fonts/drawn/ (the fonts), apps/review/src/drawn-forms.css and
apps/cloudflare/src/drawnFormsData.ts, which the Worker and the review app read.
"""

from __future__ import annotations

import hashlib
import io
import json
import re
from pathlib import Path

from fontTools.fontBuilder import FontBuilder
from fontTools.misc.timeTools import timestampSinceEpoch
from fontTools.pens.t2CharStringPen import T2CharStringPen
from fontTools.pens.transformPen import TransformPen
from fontTools.svgLib.path import parse_path

from glyph_atlas import drawn_forms

ROOT = Path(__file__).resolve().parents[1]
APP = ROOT / "apps" / "review"
OUT = APP / "static" / "fonts" / "drawn"
CSS = APP / "src" / "drawn-forms.css"
MODULE = ROOT / "apps" / "cloudflare" / "src" / "drawnFormsData.ts"
# The family of each style: the sans one is the default.
FAMILIES = {"sans": "Glyph Atlas Drawn Forms", "serif": "Glyph Atlas Drawn Forms Serif"}
# A drawing's em, with its top at the ascender: the same box an ideograph of a CJK font fills.
EM, ASCENT, DESCENT = 1000, 880, -120
# The font's dates are fixed, so the same drawings give the same file: 1 January 2026.
STAMP = timestampSinceEpoch(1767225600)


def _glyph(form: drawn_forms.DrawnForm, style: str):
    drawing = form.drawing(style)
    found = re.fullmatch(r'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 1000 1000">\s*<path d="([^"]+)"/>\s*</svg>\s*',
                         drawing.read_text(encoding="utf-8"))
    if not found:
        raise ValueError(f"{drawing.relative_to(ROOT)} is not one path in a 1000-unit em")
    pen = T2CharStringPen(EM, None)
    parse_path(found.group(1), TransformPen(pen, (1, 0, 0, -1, 0, ASCENT)))
    return pen.getCharString()


def font(style: str) -> bytes:
    """The forms in one style as an OpenType font in WOFF2, the same bytes for the same drawings."""
    family = FAMILIES[style]
    forms = sorted(drawn_forms.table().forms.values(), key=lambda form: form.char)
    names = {form.char: f"u{ord(form.char):X}" for form in forms}
    builder = FontBuilder(EM, isTTF=False)
    builder.setupGlyphOrder([".notdef", *names.values()])
    builder.setupCharacterMap({ord(char): name for char, name in names.items()})
    builder.setupCFF(family.replace(" ", ""), {"FullName": family},
                     {".notdef": T2CharStringPen(EM, None).getCharString(), **{names[form.char]: _glyph(form, style) for form in forms}}, {})
    builder.setupHorizontalMetrics({name: (EM, 0) for name in [".notdef", *names.values()]})
    builder.setupHorizontalHeader(ascent=ASCENT, descent=DESCENT)
    builder.setupNameTable({"familyName": family, "styleName": "Regular"})
    builder.setupOS2(sTypoAscender=ASCENT, sTypoDescender=DESCENT, usWinAscent=ASCENT, usWinDescent=-DESCENT)
    builder.setupPost()
    builder.setupHead(created=STAMP, modified=STAMP)
    builder.font.flavor = "woff2"
    buffer = io.BytesIO()
    builder.font.save(buffer, reorderTables=False)
    return buffer.getvalue()


def ranges(codes: list[int]) -> str:
    runs: list[list[int]] = []
    for code in sorted(codes):
        if runs and runs[-1][1] == code - 1:
            runs[-1][1] = code
        else:
            runs.append([code, code])
    return ", ".join(f"U+{a:X}" if a == b else f"U+{a:X}-{b:X}" for a, b in runs)


def css(names: dict[str, str]) -> str:
    """The stylesheet, for the file of each style."""
    table = drawn_forms.table()
    covered = ranges([ord(char) for char in table.forms])
    return ("/* Generated by scripts/build_drawn_forms.py from data/vocab/drawn-forms.yaml: the drawn forms as glyphs of\n"
            "   their private-use code points, in a sans and a serif cut. A page that shows none downloads neither. */\n"
            + "".join(f'@font-face {{\n  font-family: "{FAMILIES[style]}";\n  src: url("/fonts/drawn/{names[style]}") format("woff2");\n'
                      f"  font-display: block;\n  unicode-range: {covered};\n}}\n" for style in drawn_forms.STYLES)
            # `ScriptText` sets a drawn form in `--drawn-font`: the cut of the face the reader chose.
            + f':root {{\n  --drawn-sans: "{FAMILIES["sans"]}", sans-serif;\n  --drawn-serif: "{FAMILIES["serif"]}", serif;\n'
              "  --drawn-font: var(--drawn-sans);\n}\n"
              ":root[data-typeface=serif] { --drawn-font: var(--drawn-serif); }\n")


def module() -> str:
    """The table as the Worker reads it, its characters as escapes: a private-use character typed into
    a source file is invisible to whoever reads it."""
    table = drawn_forms.table()
    rows = "".join(f"  '\\u{{{ord(form.char):X}}}': {{ for: '{form.written_for}', script: '{form.script}', name: {json.dumps(form.name, ensure_ascii=False)} }},\n"
                   for form in sorted(table.forms.values(), key=lambda form: form.char))
    return (
        "// Written by scripts/build_drawn_forms.py from data/vocab/drawn-forms.yaml; edit neither here.\n"
        "/** The namespace and version of the site's private-use mapping, and the fonts that draw it. */\n"
        f"export const DRAWN_NAMESPACE = '{table.namespace}', DRAWN_VERSION = '{table.version}';\n"
        f"export const DRAWN_FAMILY = '{FAMILIES['sans']}', DRAWN_FAMILY_SERIF = '{FAMILIES['serif']}';\n"
        "/** Each drawn form's character, with the head of the grapheme it writes, its script and what it looks like. */\n"
        f"export const DRAWN: Record<string, {{ for: string; script: string; name: string }}> = {{\n{rows}}};\n"
    )


def main() -> int:
    OUT.mkdir(parents=True, exist_ok=True)
    for old in OUT.glob("*.woff2"):
        old.unlink()
    names = {}
    for style in drawn_forms.STYLES:
        data = font(style)
        names[style] = f"drawn-{style}-{hashlib.sha256(data).hexdigest()[:12]}.woff2"
        (OUT / names[style]).write_bytes(data)
        print(f"{style}: {len(data)} B as {names[style]}")
    CSS.write_text(css(names), encoding="utf-8")
    MODULE.write_text(module(), encoding="utf-8")
    print(f"{len(drawn_forms.table().forms)} drawn forms")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
