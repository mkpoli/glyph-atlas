"""Build the Tangut label font for the review interface, split into small files.

Noto Serif Tangut draws the Tangut labels. The whole font is about 940 KB, and a page shows a few
Tangut characters at most: every character page's script legend shows one, 𗀀 U+17000. So 𗀀 gets
a file of its own, and the rest are cut into files of CHUNK consecutive code points, each with its own
`unicode-range`, so a page downloads only the files for the characters it shows. Each file is named
by its content hash, so a browser may keep it for good.

  uv run scripts/build_tangut_font.py

Writes apps/review/static/fonts/tangut/ (the fonts and the licence) and apps/review/src/tangut-font.css.
"""
import hashlib
import io
import urllib.request
import zipfile
from pathlib import Path

from fontTools import subset
from fontTools.ttLib import TTFont

ROOT = Path(__file__).resolve().parents[1]
APP = ROOT / 'apps/review'
OUT = APP / 'static/fonts/tangut'
CSS = APP / 'src/tangut-font.css'
CACHE = ROOT / 'cache/fonts'
CHUNK = 256   # consecutive code points a file; 1–52 KB each, 1.1 MB in all against 940 KB whole
SAMPLE = 0x17000   # the script legend's sample
RELEASE = {'url': 'https://github.com/notofonts/tangut/releases/download/NotoSerifTangut-v2.170/NotoSerifTangut-v2.170.zip',
           'sha256': '741ef7bca66790c51c5f2efea3c291f5a82cc2e3992d9413a020aec26dbd75b1',
           'font': 'NotoSerifTangut/unhinted/ttf/NotoSerifTangut-Regular.ttf', 'licence': 'OFL.txt'}
# The iteration mark, the Tangut block and Tangut Supplement; no label is a component.
BLOCKS = [(0x16FE0, 0x16FE0), (0x17000, 0x187FF), (0x18D00, 0x18D7F)]


def fetch(url, sha256):
    path = CACHE / url.rsplit('/', 1)[1]
    if path.exists() and hashlib.sha256(path.read_bytes()).hexdigest() == sha256:
        return path.read_bytes()
    data = urllib.request.urlopen(url, timeout=300).read()
    assert hashlib.sha256(data).hexdigest() == sha256, f'{url} does not match its pinned hash'
    CACHE.mkdir(parents=True, exist_ok=True)
    path.write_bytes(data)
    return data


def ranges(codes):
    out = []
    for c in sorted(codes):
        if out and out[-1][1] == c - 1:
            out[-1][1] = c
        else:
            out.append([c, c])
    return ', '.join(f'U+{a:X}' if a == b else f'U+{a:X}-{b:X}' for a, b in out)


def cut(source, codes):
    font = TTFont(io.BytesIO(source), recalcTimestamp=False)
    options = subset.Options(); options.flavor = 'woff2'; options.layout_features = ['*']
    sub = subset.Subsetter(options=options); sub.populate(unicodes=codes); sub.subset(font)
    buffer = io.BytesIO(); subset.save_font(font, buffer, options)
    data = buffer.getvalue()
    name = f'tangut-{hashlib.sha256(data).hexdigest()[:12]}.woff2'
    (OUT / name).write_bytes(data)
    return (f'@font-face {{\n  font-family: "Noto Serif Tangut";\n  src: url("/fonts/tangut/{name}") format("woff2");\n'
            f'  font-display: swap;\n  unicode-range: {ranges(codes)};\n}}\n'), len(data)


def main():
    archive = zipfile.ZipFile(io.BytesIO(fetch(RELEASE['url'], RELEASE['sha256'])))
    source = archive.read(RELEASE['font'])
    drawn = sorted(c for c in TTFont(io.BytesIO(source)).getBestCmap() if any(a <= c <= b for a, b in BLOCKS))
    OUT.mkdir(parents=True, exist_ok=True)
    for old in OUT.glob('*.woff2'):
        old.unlink()
    (OUT / 'OFL.txt').write_bytes(archive.read(next(n for n in archive.namelist() if n.endswith(RELEASE['licence']))))
    rest = [c for c in drawn if c != SAMPLE]
    cuts = [cut(source, [SAMPLE])] + [cut(source, rest[i:i + CHUNK]) for i in range(0, len(rest), CHUNK)]
    CSS.write_text('/* Generated by scripts/build_tangut_font.py: Noto Serif Tangut 2.170, the legend\'s sample 𗀀 alone and\n'
                   '   the rest in files of consecutive code points, so a page downloads only the ones it shows. */\n'
                   + ''.join(face for face, _ in cuts))
    sizes = [size for _, size in cuts]
    print(f'{len(drawn)} characters in {len(cuts)} files: the sample {sizes[0]} B, the rest '
          f'{min(sizes[1:]) // 1024}–{max(sizes[1:]) // 1024} KB, {sum(sizes) // 1024} KB in all')


if __name__ == '__main__':
    main()
